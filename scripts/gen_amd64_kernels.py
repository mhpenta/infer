"""
Generate infer's amd64 matmul microkernels.

    python3 scripts/gen_amd64_kernels.py

Writes ops/kernel_amd64.s (6×16, AVX2), ops/kernel12x32_amd64.s (12×32,
AVX-512) and ops/gemv_amd64.s (one-row products over 4 or 1 panels, AVX2),
each with a float32-panel, an fp16-panel, a bf16-panel and an int8-panel
variant. The variants differ only in how a panel row is loaded: VMOVUPS for
float32, VCVTPH2PS (widening 8 or 16 halves to float32) for fp16, VPMOVZXWD
then a 16-bit left shift for bf16 (a bf16 value is the top half of a
float32), VPMOVSXBD then VCVTDQ2PS for int8 (sign-extend to 32 bits, then
convert, exactly), and in the panel stride. See the microkernel contract in
ops/kernel_go.go.
"""
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
HEADER = "// Code generated by scripts/gen_amd64_kernels.py; DO NOT EDIT.\n\n//go:build amd64 && !purego\n\n#include \"textflag.h\"\n"
NL = "\n"

# Panel formats: element type in Go, bytes per value.
GO_TYPE = {"f32": "float32", "f16": "uint16", "bf16": "uint16", "i8": "int8"}
SIZE = {"f32": 4, "f16": 2, "bf16": 2, "i8": 1}
DESCRIBE = {"f32": "float32 panel row", "f16": "fp16 panel row widened with VCVTPH2PS",
            "bf16": "bf16 panel row widened with VPMOVZXWD and VPSLLD",
            "i8": "int8 panel row widened with VPMOVSXBD and VCVTDQ2PS"}


def load_row(fmt, mem, reg):
    """Load 8 (YMM) or 16 (ZMM) panel values at mem into reg as float32."""
    if fmt == "f32":
        return [f"\tVMOVUPS {mem}, {reg}"]
    if fmt == "f16":
        return [f"\tVCVTPH2PS {mem}, {reg}"]
    if fmt == "i8":
        return [f"\tVPMOVSXBD {mem}, {reg}", f"\tVCVTDQ2PS {reg}, {reg}"]
    return [f"\tVPMOVZXWD {mem}, {reg}", f"\tVPSLLD $16, {reg}, {reg}"]


def kernel6x16(name, fmt):
    row = 16 * SIZE[fmt]  # bytes of one 16-wide panel row

    def load(off):
        return load_row(fmt, f"{off}(SI)", "Y12") + load_row(fmt, f"{off + row // 2}(SI)", "Y13")

    def step(boff, aoff):
        lines = load(boff)
        for r in range(6):
            y = "Y14" if r % 2 == 0 else "Y15"
            lines += [f"\tVBROADCASTSS {aoff + 4 * r}(R8), {y}",
                      f"\tVFMADD231PS  Y12, {y}, Y{2 * r}",
                      f"\tVFMADD231PS  Y13, {y}, Y{2 * r + 1}"]
        return lines

    def stores(bias=False, acc=False):
        lines = []
        for r in range(6):
            a, b = f"Y{2 * r}", f"Y{2 * r + 1}"
            if bias:
                lines += [f"\tVADDPS Y12, {a}, {a}", f"\tVADDPS Y13, {b}, {b}"]
            if acc:
                lines += [f"\tVADDPS (DI), {a}, {a}", f"\tVADDPS 32(DI), {b}, {b}"]
            lines += [f"\tVMOVUPS {a}, (DI)", f"\tVMOVUPS {b}, 32(DI)"]
            if r < 5:
                lines.append("\tADDQ    R9, DI")
        return lines + ["\tVZEROUPPER", "\tRET"]

    body4 = []
    for s in range(4):
        body4 += [f"\t// k step {s}"] + step(row * s, 24 * s)
    panel = DESCRIBE[fmt]
    return f"""
// func {name}(a *float32, b *{GO_TYPE[fmt]}, k int, c *float32, ldc int, bias *float32, mode int)
//
// Outer-product microkernel; see the contract in kernel_go.go. Per k step it
// loads one 16-wide {panel} (Y12, Y13),
// broadcasts the 6 values of the packed a strip (alternating Y14, Y15) and
// issues 12 fused multiply-adds into Y0-Y11, where Y(2r) and Y(2r+1) hold
// columns 0-7 and 8-15 of output row r. The main loop runs 4 k steps per
// iteration; a second loop takes the remaining 0-3. The epilogue writes the
// six rows to c, ldc elements apart.
TEXT ·{name}(SB), NOSPLIT, $0-56
	MOVQ a+0(FP), R8
	MOVQ b+8(FP), SI
	MOVQ k+16(FP), CX
	MOVQ c+24(FP), DI
	MOVQ ldc+32(FP), R9
	MOVQ bias+40(FP), R10
	MOVQ mode+48(FP), R11
	SHLQ $2, R9 // ldc in bytes

{NL.join(f'	VXORPS Y{i}, Y{i}, Y{i}' for i in range(12))}

	MOVQ  CX, DX
	SHRQ  $2, DX // iterations of 4 k steps
	ANDQ  $3, CX // remaining k steps
	TESTQ DX, DX
	JZ    tail

loop4:
{NL.join(body4)}
	ADDQ ${4 * row}, SI
	ADDQ $96, R8
	DECQ DX
	JNZ  loop4

tail:
	TESTQ CX, CX
	JZ    epilogue

loop1:
{NL.join(step(0, 0))}
	ADDQ ${row}, SI
	ADDQ $24, R8
	DECQ CX
	JNZ  loop1

epilogue:
	CMPQ R11, $2
	JEQ  accumulate
	CMPQ R11, $1
	JEQ  storebias

{NL.join(stores())}

storebias:
	VMOVUPS (R10), Y12
	VMOVUPS 32(R10), Y13
{NL.join(stores(bias=True))}

accumulate:
{NL.join(stores(acc=True))}
"""


def kernel12x32(name, fmt):
    row = 16 * SIZE[fmt]

    def step(boff, aoff):
        lines = load_row(fmt, f"{boff}(SI)", "Z24") + load_row(fmt, f"{boff}(DI)", "Z25")
        for r in range(12):
            src = "R8" if r < 6 else "R9"
            z = f"Z{26 + r % 6}"
            lines += [f"\tVBROADCASTSS {aoff + 4 * (r % 6)}({src}), {z}",
                      f"\tVFMADD231PS  Z24, {z}, Z{2 * r}",
                      f"\tVFMADD231PS  Z25, {z}, Z{2 * r + 1}"]
        return lines

    def stores(bias=False, acc=False):
        lines = []
        for r in range(12):
            a, b = f"Z{2 * r}", f"Z{2 * r + 1}"
            if bias:
                lines += [f"\tVADDPS Z24, {a}, {a}", f"\tVADDPS Z25, {b}, {b}"]
            if acc:
                lines += [f"\tVADDPS (DX), {a}, {a}", f"\tVADDPS 64(DX), {b}, {b}"]
            lines += [f"\tVMOVUPS {a}, (DX)", f"\tVMOVUPS {b}, 64(DX)"]
            if r < 11:
                lines.append("\tADDQ    R10, DX")
        return lines + ["\tVZEROUPPER", "\tRET"]

    btype = GO_TYPE[fmt]
    panel = {"f32": "row", "f16": "fp16 row widened with VCVTPH2PS", "bf16": "bf16 row (VPMOVZXWD, VPSLLD)",
             "i8": "int8 row (VPMOVSXBD, VCVTDQ2PS)"}[fmt]
    return f"""
// func {name}(a0, a1 *float32, b0, b1 *{btype}, k int, c *float32, ldc int, bias *float32, mode int)
//
// Wide outer-product microkernel; see the contract in kernel_go.go. Per k
// step it loads one 16-wide {panel} from each panel (Z24 from b0, Z25
// from b1), broadcasts the 6 values of each packed strip (Z26-Z31, rows 0-5
// from a0 then rows 6-11 from a1) and issues 24 fused multiply-adds into
// Z0-Z23, where Z(2r) and Z(2r+1) hold columns 0-15 and 16-31 of output row
// r. The main loop runs 2 k steps per iteration, then one more if k is odd.
// The epilogue writes the twelve rows to c, ldc elements apart.
TEXT ·{name}(SB), NOSPLIT, $0-72
	MOVQ a0+0(FP), R8
	MOVQ a1+8(FP), R9
	MOVQ b0+16(FP), SI
	MOVQ b1+24(FP), DI
	MOVQ k+32(FP), CX
	MOVQ c+40(FP), DX
	MOVQ ldc+48(FP), R10
	MOVQ bias+56(FP), R11
	MOVQ mode+64(FP), R12
	SHLQ $2, R10 // ldc in bytes

{NL.join(f'	VPXORD Z{i}, Z{i}, Z{i}' for i in range(24))}

	MOVQ  CX, BX
	SHRQ  $1, BX // iterations of 2 k steps
	ANDQ  $1, CX // one more step if k is odd
	TESTQ BX, BX
	JZ    tail

loop2:
	// k step 0
{NL.join(step(0, 0))}
	// k step 1
{NL.join(step(row, 24))}
	ADDQ ${2 * row}, SI
	ADDQ ${2 * row}, DI
	ADDQ $48, R8
	ADDQ $48, R9
	DECQ BX
	JNZ  loop2

tail:
	TESTQ CX, CX
	JZ    epilogue
{NL.join(step(0, 0))}

epilogue:
	CMPQ R12, $2
	JEQ  accumulate
	CMPQ R12, $1
	JEQ  storebias

{NL.join(stores())}

storebias:
	VMOVUPS (R11), Z24
	VMOVUPS 64(R11), Z25
{NL.join(stores(bias=True))}

accumulate:
{NL.join(stores(acc=True))}
"""


def gemv(name, panels, fmt):
    """One row of a times panels consecutive 16-wide panels, panelStride
    values apart. Like the 6×16 kernels, each output is one sequential FMA
    chain along k, so results are bit-identical to theirs."""
    row = 16 * SIZE[fmt]
    ptrs = ["SI", "R9", "R10", "R11"][:panels]
    acc = lambda p, h: f"Y{2 * p + h}"

    def step(boff, aoff):
        lines = [f"\tVBROADCASTSS {aoff}(DI), Y15"]
        for p, ptr in enumerate(ptrs):
            if fmt != "f32":
                t0, t1 = f"Y{8 + 2 * (p % 3)}", f"Y{9 + 2 * (p % 3)}"
                lines += load_row(fmt, f"{boff}({ptr})", t0) + load_row(fmt, f"{boff + row // 2}({ptr})", t1)
                lines += [f"\tVFMADD231PS {t0}, Y15, {acc(p, 0)}", f"\tVFMADD231PS {t1}, Y15, {acc(p, 1)}"]
            else:
                lines += [f"\tVFMADD231PS {boff}({ptr}), Y15, {acc(p, 0)}", f"\tVFMADD231PS {boff + 32}({ptr}), Y15, {acc(p, 1)}"]
        return lines

    setup = []
    if panels > 1:
        shift = {1: 0, 2: 1, 4: 2}[SIZE[fmt]]  # stride in bytes: values × 1, 2 or 4
        setup = ([f"\tSHLQ ${shift}, R8"] if shift else []) + ["\tLEAQ (SI)(R8*1), R9"]
        if panels > 2:
            setup.append("\tLEAQ (R9)(R8*1), R10")
        if panels > 3:
            setup.append("\tLEAQ (R10)(R8*1), R11")
    adds = "\n".join(f"\tADDQ ${2 * row}, {ptr}" for ptr in ptrs)
    adds1 = "\n".join(f"\tADDQ ${row}, {ptr}" for ptr in ptrs)
    stores = "\n".join(f"\tVMOVUPS {acc(p, h)}, {64 * p + 32 * h}(DX)" for p in range(panels) for h in range(2))
    zero = "\n".join(f"\tVXORPS {acc(p, h)}, {acc(p, h)}, {acc(p, h)}" for p in range(panels) for h in range(2))
    btype = GO_TYPE[fmt]
    return f"""
// func {name}(a *float32, b *{btype}, panelStride int, k int, out *[{16 * panels}]float32)
//
// out[16p + j] = sum over kk < k of a[kk]·b[p][kk][j] for {panels} panel(s), k >= 1.
// Per k step: broadcast a[kk] (Y15) and fused multiply-add one 16-wide row of
// each panel into its two accumulators. The main loop takes 2 k steps.
TEXT ·{name}(SB), NOSPLIT, $0-40
	MOVQ a+0(FP), DI
	MOVQ b+8(FP), SI
	MOVQ panelStride+16(FP), R8
	MOVQ k+24(FP), CX
	MOVQ out+32(FP), DX
{NL.join(setup)}

{zero}

	MOVQ  CX, BX
	SHRQ  $1, BX
	ANDQ  $1, CX
	TESTQ BX, BX
	JZ    tail

loop2:
{NL.join(step(0, 0))}
{NL.join(step(row, 4))}
{adds}
	ADDQ $8, DI
	DECQ BX
	JNZ  loop2

tail:
	TESTQ CX, CX
	JZ    done
{NL.join(step(0, 0))}

done:
{stores}
	VZEROUPPER
	RET
"""


def write(path, text):
    with open(os.path.join(ROOT, path), "w") as f:
        f.write(text)


# Kernel name suffixes: float32 panels none, fp16 H, bf16 B, int8 I.
FORMATS = [("", "f32"), ("H", "f16"), ("B", "bf16"), ("I", "i8")]
write("ops/kernel_amd64.s", HEADER + "".join(kernel6x16("kernel6x16AVX2" + sfx, f) for sfx, f in FORMATS))
write("ops/kernel12x32_amd64.s", HEADER + "".join(kernel12x32("kernel12x32AVX512" + sfx, f) for sfx, f in FORMATS))
write("ops/gemv_amd64.s", HEADER + "".join(gemv(f"gemv{p}AVX2" + sfx, p, f) for sfx, f in FORMATS for p in (4, 1)))
