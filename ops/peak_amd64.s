// func peakAVX2(iters int)
//
// 12 independent FMA chains on registers only: enough to keep both FMA ports
// busy despite their latency, so the loop runs at the core's peak rate. The
// operands are zero so the values never grow.
TEXT ·peakAVX2(SB), NOSPLIT, $0-8
	MOVQ iters+0(FP), CX
	VXORPS Y0, Y0, Y0
	VXORPS Y1, Y1, Y1
	VXORPS Y2, Y2, Y2
	VXORPS Y3, Y3, Y3
	VXORPS Y4, Y4, Y4
	VXORPS Y5, Y5, Y5
	VXORPS Y6, Y6, Y6
	VXORPS Y7, Y7, Y7
	VXORPS Y8, Y8, Y8
	VXORPS Y9, Y9, Y9
	VXORPS Y10, Y10, Y10
	VXORPS Y11, Y11, Y11
	VXORPS Y12, Y12, Y12
	VXORPS Y13, Y13, Y13

peakloop:
	VFMADD231PS Y12, Y13, Y0
	VFMADD231PS Y12, Y13, Y1
	VFMADD231PS Y12, Y13, Y2
	VFMADD231PS Y12, Y13, Y3
	VFMADD231PS Y12, Y13, Y4
	VFMADD231PS Y12, Y13, Y5
	VFMADD231PS Y12, Y13, Y6
	VFMADD231PS Y12, Y13, Y7
	VFMADD231PS Y12, Y13, Y8
	VFMADD231PS Y12, Y13, Y9
	VFMADD231PS Y12, Y13, Y10
	VFMADD231PS Y12, Y13, Y11
	DECQ CX
	JNZ  peakloop

	VZEROUPPER
	RET

// func peakAVX512(iters int)
