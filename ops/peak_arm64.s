// func peakNEON(iters int)
//
// 24 independent FMA chains on registers only, so the loop runs at the
// core's peak rate. The operands are zero so the values never grow.
TEXT ·peakNEON(SB), NOSPLIT, $0-8
	MOVD iters+0(FP), R0
	VEOR V0.B16, V0.B16, V0.B16
	VEOR V1.B16, V1.B16, V1.B16
	VEOR V2.B16, V2.B16, V2.B16
	VEOR V3.B16, V3.B16, V3.B16
	VEOR V4.B16, V4.B16, V4.B16
	VEOR V5.B16, V5.B16, V5.B16
	VEOR V6.B16, V6.B16, V6.B16
	VEOR V7.B16, V7.B16, V7.B16
	VEOR V8.B16, V8.B16, V8.B16
	VEOR V9.B16, V9.B16, V9.B16
	VEOR V10.B16, V10.B16, V10.B16
	VEOR V11.B16, V11.B16, V11.B16
	VEOR V12.B16, V12.B16, V12.B16
	VEOR V13.B16, V13.B16, V13.B16
	VEOR V14.B16, V14.B16, V14.B16
	VEOR V15.B16, V15.B16, V15.B16
	VEOR V16.B16, V16.B16, V16.B16
	VEOR V17.B16, V17.B16, V17.B16
	VEOR V18.B16, V18.B16, V18.B16
	VEOR V19.B16, V19.B16, V19.B16
	VEOR V20.B16, V20.B16, V20.B16
	VEOR V21.B16, V21.B16, V21.B16
	VEOR V22.B16, V22.B16, V22.B16
	VEOR V23.B16, V23.B16, V23.B16
	VEOR V24.B16, V24.B16, V24.B16
	VEOR V25.B16, V25.B16, V25.B16

peakloop:
	VFMLA V24.S4, V25.S4, V0.S4
	VFMLA V24.S4, V25.S4, V1.S4
	VFMLA V24.S4, V25.S4, V2.S4
	VFMLA V24.S4, V25.S4, V3.S4
	VFMLA V24.S4, V25.S4, V4.S4
	VFMLA V24.S4, V25.S4, V5.S4
	VFMLA V24.S4, V25.S4, V6.S4
	VFMLA V24.S4, V25.S4, V7.S4
	VFMLA V24.S4, V25.S4, V8.S4
	VFMLA V24.S4, V25.S4, V9.S4
	VFMLA V24.S4, V25.S4, V10.S4
	VFMLA V24.S4, V25.S4, V11.S4
	VFMLA V24.S4, V25.S4, V12.S4
	VFMLA V24.S4, V25.S4, V13.S4
	VFMLA V24.S4, V25.S4, V14.S4
	VFMLA V24.S4, V25.S4, V15.S4
	VFMLA V24.S4, V25.S4, V16.S4
	VFMLA V24.S4, V25.S4, V17.S4
	VFMLA V24.S4, V25.S4, V18.S4
	VFMLA V24.S4, V25.S4, V19.S4
	VFMLA V24.S4, V25.S4, V20.S4
	VFMLA V24.S4, V25.S4, V21.S4
	VFMLA V24.S4, V25.S4, V22.S4
	VFMLA V24.S4, V25.S4, V23.S4
	SUBS $1, R0, R0
	BNE  peakloop
	RET
